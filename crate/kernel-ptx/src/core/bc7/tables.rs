const fn build_subset_idx(table: &[u8; 64 * 16]) -> [SubsetIdx; 64] {
    let mut out = [SubsetIdx {
        idx: [[0i32; 16]; 3],
        total: [0usize; 3],
    }; 64];
    let mut partition = 0usize;
    while partition < 64 {
        let mut index = 0usize;
        while index < 16 {
            let pp = table[partition * 16 + index] as usize;
            out[partition].idx[pp][out[partition].total[pp]] = index as i32;
            out[partition].total[pp] += 1;
            index += 1;
        }
        partition += 1;
    }
    out
}

