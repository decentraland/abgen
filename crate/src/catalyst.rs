    #[test]
    fn metadata_only_matches_upstream_classification_rules() {
        let none = scene_with(&[("tex/a.png", "h1")], serde_json::json!({}));
        assert!(none.metadata_only_hashes().is_empty());

        let root_thumb = scene_with(
            &[("autogenerated-thumbnail.png", "h1")],
            serde_json::json!({}),
        );
        assert_eq!(root_thumb.metadata_only_hashes().len(), 1);

        let cased = scene_with(
            &[("Assets/AutoGenerated-Thumbnail.PNG", "h1")],
            serde_json::json!({}),
        );
        assert_eq!(cased.metadata_only_hashes().len(), 1);

        let lookalike = scene_with(
            &[
                ("assets/my-autogenerated-thumbnail.png", "h1"),
                ("assets/autogenerated-thumbnail.png.bak", "h2"),
            ],
            serde_json::json!({}),
        );
        assert!(lookalike.metadata_only_hashes().is_empty());

        let navmap_cased = scene_with(
            &[("Assets/Thumb.png", "h1")],
            serde_json::json!({"display": {"navmapThumbnail": "assets/thumb.PNG"}}),
        );
        assert_eq!(
            navmap_cased.metadata_only_hashes().into_iter().next(),
            Some("h1".to_string())
        );

        let dangling = scene_with(
            &[("tex/a.png", "h1")],
            serde_json::json!({"display": {"navmapThumbnail": "missing.png"}}),
        );
        assert!(dangling.metadata_only_hashes().is_empty());

        let non_string = scene_with(
            &[("tex/a.png", "h1")],
            serde_json::json!({"display": {"navmapThumbnail": 7}}),
        );
        assert!(non_string.metadata_only_hashes().is_empty());

        let no_display = scene_with(&[("tex/a.png", "h1")], serde_json::json!({"display": "x"}));
        assert!(no_display.metadata_only_hashes().is_empty());
    }
